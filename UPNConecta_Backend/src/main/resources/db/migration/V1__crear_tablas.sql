-- =====================================================================
-- UPN Conecta - Tablas para la HU2.03 "Calificar un área de la sede"
-- Basado en el diagrama E-R de la S08 (UNIVERSIDAD, SEDE, USUARIO,
-- CRITERIO, RESENA y CALIFICACION). Las tablas de cursos, docentes y
-- reportes se agregarán en otra migración cuando se implementen sus HU.
-- =====================================================================

CREATE TABLE universidad (
    id_universidad  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(120) NOT NULL,
    siglas          VARCHAR(10)  NOT NULL,
    dominio_correo  VARCHAR(60)  NOT NULL UNIQUE
);

CREATE TABLE sede (
    id_sede         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_universidad  INTEGER      NOT NULL REFERENCES universidad (id_universidad),
    -- codigo: identificador corto que usa la app (ej. "los_olivos")
    codigo          VARCHAR(30)  NOT NULL UNIQUE,
    nombre          VARCHAR(80)  NOT NULL,
    direccion       VARCHAR(150) NOT NULL
);

CREATE TABLE usuario (
    codigo          VARCHAR(20)  PRIMARY KEY,
    id_universidad  INTEGER      NOT NULL REFERENCES universidad (id_universidad),
    correo          VARCHAR(80)  NOT NULL UNIQUE,
    nombre_completo VARCHAR(100) NOT NULL,
    rol             VARCHAR(10)  NOT NULL CHECK (rol IN ('ALUMNO', 'DOCENTE')),
    verificado      BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE criterio (
    id_criterio     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- area: agrupa los criterios (infraestructura, limpieza, gestion, sostenibilidad)
    area            VARCHAR(30)  NOT NULL,
    nombre          VARCHAR(60)  NOT NULL,
    orden           INTEGER      NOT NULL,
    CONSTRAINT uq_criterio_area_nombre UNIQUE (area, nombre)
);

CREATE TABLE resena (
    id_resena       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario      VARCHAR(20)  NOT NULL REFERENCES usuario (codigo),
    id_sede         INTEGER      NOT NULL REFERENCES sede (id_sede),
    area            VARCHAR(30)  NOT NULL,
    periodo         VARCHAR(10)  NOT NULL,
    experiencia     INTEGER      NOT NULL CHECK (experiencia BETWEEN 1 AND 5),
    comentario      VARCHAR(500),
    es_anonima      BOOLEAN      NOT NULL DEFAULT FALSE,
    sin_reciclaje   BOOLEAN      NOT NULL DEFAULT FALSE,
    fecha           TIMESTAMP    NOT NULL,
    -- HU2.03: una sola evaluación por usuario, sede, área y ciclo
    CONSTRAINT uq_resena_usuario_sede_area_periodo UNIQUE (id_usuario, id_sede, area, periodo)
);

CREATE TABLE calificacion (
    id_resena       INTEGER NOT NULL REFERENCES resena (id_resena) ON DELETE CASCADE,
    id_criterio     INTEGER NOT NULL REFERENCES criterio (id_criterio),
    puntaje         INTEGER NOT NULL CHECK (puntaje BETWEEN 1 AND 5),
    PRIMARY KEY (id_resena, id_criterio)
);

CREATE INDEX idx_resena_sede_area ON resena (id_sede, area, periodo);
